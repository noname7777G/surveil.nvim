---@class surveil
---@field allCards card[]
---@field trimmedCards card[]?
---@field defaultQuery string?
---@field bulkDataPath string
---@field sortPredicate string?
---@field cacheDir string
---@field curlArgs string
local M = {}

---@class surveilOpts
---@field bulkDataPath string?
---@field defaultQuery string?
---@field sortPredicate string?
---@field cacheDir string?

M.bulkDataPath = vim.fn.stdpath("cache") .. "/oracle_cards.json"
M.curlArgs = " --header User-Agent:nvim-surveil --header Accept:*/* --silent "
M.cacheDir = vim.fn.stdpath("cache")

---@param opts surveilOpts?
M.setup = function(opts)
  opts = opts or {}


  M.bulkDataPath = opts.bulkDataPath or M.bulkDataPath
  M.defaultQuery = opts.defaultQuery
  M.sortPredicate = opts.sortPredicate
  M.cacheDir = opts.cacheDir or M.cacheDir
end

---Mostly for internal use but maybe you can get some use out of it.
---@param query string: The query to run. For a full list of currently implemented syntax, please see README.md. Returns all cards if empty or nil, respecting allCards.
---@param allCards boolean?: If true will use all loaded cards, rather than the table of cards generated by the default query.
---@return table?: The results of the query or nil if no cards are loaded. Will return an empty table if there are no results.
M.query = function(query, allCards)
  if M.allCards == nil then
    M.loadCards()
  end

  local target

  if allCards then
    target = M.allCards
  else
    target = M.trimmedCards or M.allCards
  end

  if not target then return nil end

  if query == "" or query == nil then
    return target
  end

  return querySession.queryTable(target, query)
end

---Set the query used to filter out entirely unwanted cards, such as art carts and tokens.
---Sets the primary table to the result of the given query.
---@param query string: The query to run.
M.setDefaultQuery = function(query)
  M.defaultQuery = query
  if M.defaultQuery then
    M.trimmedCards = M.query(M.defaultQuery, true)
  else
    M.trimmedCards = nil
  end
end

local function stripData(rawJsonObj)
  local oracleObjects = {}
  ---@cast oracleObjects card[]

  local nameMaxLen = 0
  local longestCardName = ""
  local typeLineMaxLen = 0
  local longestTypeLineCardName = ""
  local manaCostMaxLen = 0

  for _, card in ipairs(rawJsonObj) do
    if card.layout == "reversible_card" then goto continue end

    local oracleObject = oracleObjects[card.oracle_id or card.card_faces[1].oracle_id]

    if oracleObject then
      if card.games then
        for _, game in ipairs(card.games) do
          oracleObject.availabilities[game] = true
        end
      end

      oracleObject.sets[#oracleObject.sets + 1] = card.set
    else
      card.arena_id = nil
      card.id = nil
      card.lang = nil
      card.mtgo_id = nil
      card.mtgo_foil_id = nil
      card.multiverse_ids = nil
      card.resource_id = nil
      card.tcgplayer_id = nil        -- To remain nil until they stop union busting
      card.tcgplayer_etched_id = nil -- To remain nil until they stop union busting
      card.cardmarket_id = nil
      card.object = nil
      card.scryfall_uri = nil
      card.uri = nil

      card.artist = nil
      card.artist_ids = nil
      card.booster = nil
      card.border_color = nil
      card.card_back_id = nil
      card.collector_number = nil
      card.digital = nil
      card.finishes = nil
      card.flavor_text = nil
      card.frame_effects = nil
      card.frame = nil
      card.full_art = nil

      card.availabilities = {}
      for _, game in ipairs(card.games) do
        card.availabilities[game] = true
      end
      card.games = nil

      card.highres_image = nil
      card.illustration_id = nil
      card.image_status = nil
      card.image_uris = nil
      card.oversized = nil
      card.prices = nil
      card.printed_name = nil
      card.printed_text = nil
      card.printed_type_line = nil
      card.promo = nil
      card.promo_types = nil
      card.purchase_uris = nil
      card.rarity = nil
      card.related_uris = nil
      card.released_at = nil
      card.reprint = nil
      card.scryfall_set_uri = nil
      card.set_name = nil
      card.search_uri = nil
      card.set_type = nil
      card.set_uri = nil

      card.sets = {}
      card.sets[1] = card.set
      card.set = nil

      card.set_id = nil
      card.story_spotlight = nil
      card.textless = nil
      card.variation = nil
      card.variation_of = nil
      card.security_stamp = nil
      card.watermark = nil
      card.preview = nil

      card.foil = nil
      card.nonfoil = nil

      if card.card_faces then
        for _, face in ipairs(card.card_faces) do
          face.artist = nil
          face.artist_id = nil
          face.flavor_text = nil
          face.illustration_id = nil
          face.image_uris = nil
          face.printed_name = nil
          face.printed_text = nil
          face.printed_type_line = nil
          face.watermark = nil
        end
      end

      ---@cast card card

      if card.type_line then
        card.type_line = card.type_line:gsub("\226\128\148", "-")
      end

      if nameMaxLen < #card.name then
        nameMaxLen = #card.name
        longestCardName = card.name
      end

      if typeLineMaxLen < #card.type_line then
        typeLineMaxLen = #card.type_line
        longestTypeLineCardName = card.name
      end

      typeLineMaxLen = math.max(#card.type_line, typeLineMaxLen)
      if card.mana_cost then
        manaCostMaxLen = math.max(#card.mana_cost, manaCostMaxLen)
      end


      card.nameNoEpithet = card.name:match("^([^,]+),")

      oracleObjects[card.oracle_id or card.card_faces[1].oracle_id] = card
    end
    ::continue::
  end

  local orderedList = {}
  for _, card in pairs(oracleObjects) do
    table.insert(orderedList, card)
  end

  --vim.print(longestCardName .. " is " .. nameMaxLen .. " characters long.")
  --vim.print("The type line of " .. longestTypeLineCardName .. " is " .. typeLineMaxLen .. " characters long.")
  --vim.print(manaCostMaxLen)

  return orderedList
end

---@param skipDownload string?
M.updateCards = function(skipDownload)
  if skipDownload ~= "skipDownload" then
    local tempFileName = os.tmpname()

    local ok, str, code = os.execute("curl https://api.scryfall.com/bulk-data/default-cards" ..
      M.curlArgs .. "> " .. tempFileName)

    if not ok then
      print(str .. code)
      return
    end

    local tempFile = io.open(tempFileName)
    if tempFile == nil then
      print "Issue opening temp file"
      return
    end
    local json = tempFile:read()

    local jsonObj = vim.json.decode(json, { object = true, array = true })
    os.execute("curl " .. jsonObj.download_uri .. M.curlArgs .. "-o " .. M.cacheDir .. "/raw_bulk.json")
  end

  local rawBulkFile = io.open(M.cacheDir .. "/raw_bulk.json", "r")
  if not rawBulkFile then
    print "Issue opening raw bulk data."
    return
  end

  local rawJson = rawBulkFile:read("a")
  local rawJsonObj = vim.json.decode(rawJson, { object = true, array = true })

  local oracleObjects = stripData(rawJsonObj)
  local oracleObjectsJson = vim.json.encode(oracleObjects)

  local bulkFile = io.open(M.bulkDataPath, "w+")
  if not bulkFile then
    print "Issue opening bulk data file."
    return
  end

  bulkFile:write(oracleObjectsJson)
  io.close(bulkFile)
end


M.loadCards = function()
  local bulkDataFile = io.open(M.bulkDataPath)

  if bulkDataFile then
    local bulkDataJson = bulkDataFile:read("a")
    M.allCards = vim.json.decode(bulkDataJson, { object = true, array = true })
  else
    vim.ui.input({
      prompt = "No card data found, would you like to download card data? [y/N]:",
      default = "n",
    }, function(input)
      if input == "y" or input == "Y" then
        M.updateCards()

        bulkDataFile = io.open(M.bulkDataPath)

        if bulkDataFile then
          local bulkDataJson = bulkDataFile:read("a")
          M.allCards = vim.json.decode(bulkDataJson, { object = true, array = true })
        else
          vim.print("Error loading bulk data.")
        end
      end
    end)
  end

  if M.sortPredicate then
    M.sortList(M.allCards, M.sortPredicate)
  end

  for _, v in pairs(M.allCards) do
    ---@cast v card
    v.colors = Set(v.colors or {})
    v.color_identity = Set(v.color_identity or {})
    v.color_indicator = Set(v.color_indicator or {})
    v.produced_mana = Set(v.produced_mana or {})
  end

  if M.defaultQuery then
    M.trimmedCards = M.query(M.defaultQuery, true)
  end
end

---@param field string
M.setSortPredicate = function(field)
  M.sortPredicate = field

  if M.allCards then
    M.sortList(M.allCards, field)
    if M.trimmedCards then
      M.trimmedCards = querySession.queryTable(M.allCards, M.defaultQuery)
    end
  end
end

---@param list table
---@param field string
M.sortList = function(list, field)
  if field == "edhrec_rank" then
    table.sort(list, function(a, b)
      local aV = a["edhrec_rank"] or 9999999
      if aV == 0 then
        aV = 9999999
      end

      local bV = b[field] or 9999999
      if bV == 0 then
        bV = 9999999
      end

      return aV < bV
    end)
  else
    table.sort(list, function(a, b)
      local aV = utils.evaluatePT(a[field])
      local bV = utils.evaluatePT(b[field])

      return aV < bV
    end)
  end
end

---Open the picker window.
---@param prequery string?: Use this to further narrow down cards. Ideal for narrowing by format, color identity for commander, available game types.
---@param allCards boolean?: If true will use all loaded cards, rather than the table of cards generated by the default query. Will still run the prequery, if given.
M.picker = function(prequery, allCards)
  if not M.allCards then
    M.loadCards()
  end

  local target

  if allCards then
    target = M.allCards
  else
    target = M.trimmedCards or M.allCards
  end

  if prequery then
    target = querySession.queryTable(target, prequery)
  end

  picker:ShowMenu(target)
end

---Use this to free up processing power without having to restart Neovim.
---Will even unload user lists
M.unloadCards = function()
  M.allCards = nil
  M.trimmedCards = nil
  vim.print "Unloaded all cards."
end

return M
